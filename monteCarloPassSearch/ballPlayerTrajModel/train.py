def pick_device(name: str, local_rank: int, is_distributed: bool) -> torch.device:
    if is_distributed:
        return torch.device(f"cuda:{local_rank}")
    if name == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    return torch.device(name)


