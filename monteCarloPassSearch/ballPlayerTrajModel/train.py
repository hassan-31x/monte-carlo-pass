def init_distributed(args: argparse.Namespace) -> Tuple[bool, int, int, int]:
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    rank = int(os.environ.get("RANK", "0"))
    local_rank = int(os.environ.get("LOCAL_RANK", "0"))

    use_distributed = bool(args.distributed and world_size > 1)
    if not use_distributed:
        return False, 0, 0, 1

    if args.dist_backend == "nccl" and not torch.cuda.is_available():
        raise RuntimeError("NCCL backend requires CUDA, but CUDA is unavailable.")

    if torch.cuda.is_available():
        torch.cuda.set_device(local_rank)

    dist.init_process_group(backend=args.dist_backend)
    return True, rank, local_rank, world_size


def cleanup_distributed(is_distributed: bool) -> None:
    if is_distributed and dist.is_available() and dist.is_initialized():
        dist.destroy_process_group()


def set_seed(seed: int, rank: int = 0) -> None:
    effective_seed = int(seed) + int(rank)
    random.seed(effective_seed)
    np.random.seed(effective_seed)
    torch.manual_seed(effective_seed)
