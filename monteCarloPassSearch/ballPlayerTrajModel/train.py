                                alpha_bar = diffusion_alpha_bars.index_select(0, t_index).to(dtype=hist_x.dtype)
                                alpha_bar = alpha_bar.view(bsz, 1, 1)
                                alpha_bar_scalar = alpha_bar.view(bsz)
                                aux_batch_mask = torch.ones((bsz,), device=hist_x.device, dtype=torch.bool)
                                if int(diffusion_aux_max_timestep) >= 0:
                                    aux_batch_mask = t_index <= int(diffusion_aux_max_timestep)

