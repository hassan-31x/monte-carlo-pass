                            # Supervise trajectory only on GT-continue frames.
                            step_dim_mask_for_loss = step_dim_mask_for_loss & future_continue_mask.unsqueeze(-1).unsqueeze(-1)
                            if teacher_ball_steps > 0:
                                ball_dim_count = min(delta_dim, step_dim_mask_for_loss.shape[-1])
