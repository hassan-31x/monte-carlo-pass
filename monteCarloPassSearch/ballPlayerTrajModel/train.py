                            if float(delta_clip_multiplier) > 0.0:
                                delta_raw_for_oob = delta_raw_for_oob.clone()
                                speed_xy = torch.linalg.norm(delta_raw_for_oob[..., :2], dim=-1)
                                is_ball = target_idx == int(ball_entity_idx)
