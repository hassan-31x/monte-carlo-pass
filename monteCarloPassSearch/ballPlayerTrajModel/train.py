                                    delta_raw=delta_raw_pred,
                                    valid_mask=valid_seq,
                                    entity_type=entity_type,
                                    still_speed_threshold=float(still_speed_threshold),
                                    window_steps=int(still_window_steps),
                                    min_fraction=float(still_min_fraction),
                                    max_still_agents=int(max_still_agents),
                                    ball_idx=ball_entity_idx,
                                    active_step_mask=active_step_mask,
